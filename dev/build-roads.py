# The cardio road's painted pieces (a worn dirt track and the cobbled lane it is paved into, made in Gemini to match the ground tiles: long level
# strips on magenta, one per row) cut into short lengths with soft ends and packed into icons/roads.webp,
# with their places in js/map/roads-atlas.js. Generic pictures, so the sheet lives in the repo.
#
#   python dev/build-roads.py dev/art-roads/sheet2-tracks.png dev/art-roads/sheet3-paved.png
#
# Only the first ROWS strips are used (the capture of the fourth caught the mouse pointer).
import sys, os, json
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from defringe import defringe

ROWS = 3
PER_ROW = 2          # pieces cut from each strip
RATIO = 4.4          # a piece's length over its width (two must fit in one strip's usable length)
FADE = 0.12          # how much of each end fades out
HEIGHT = 44          # a piece's height in the atlas
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def magenta(p):
    r, g, b, _ = p
    return r - g > 35 and b - g > 10

def cut_sheet(path):
    sheet = Image.open(path).convert('RGBA')
    W, H = sheet.size
    px = sheet.load()
    # The strips: runs of rows where most of the middle of the row is track, not magenta.
    bands, start = [], None
    for y in range(H):
        track = sum(1 for x in range(W // 4, 3 * W // 4, 4) if not magenta(px[x, y])) > (W // 2) / 4 * 0.8
        if track and start is None: start = y
        if not track and start is not None:
            if y - start > 40: bands.append((start, y))
            start = None
    if start is not None and H - start > 40: bands.append((start, H))
    bands = bands[:ROWS]

    # Where the strips' own (pink-blended) ends are: keep well inside them.
    def span(y0, y1):
        ym = (y0 + y1) // 2
        xs = [x for x in range(W) if not magenta(px[x, ym])]
        return xs[0] + 40, xs[-1] - 40

    pieces = []
    for y0, y1 in bands:
        y0, y1 = y0 + 3, y1 - 3                       # off the magenta seams between strips
        x0, x1 = span(y0, y1)
        length = round((y1 - y0) * RATIO)
        room = (x1 - x0) - length * PER_ROW
        for i in range(PER_ROW):
            sx = x0 + room * (i + 1) // (PER_ROW + 1) + i * length
            im = sheet.crop((sx, y0, sx + length, y1))
            ip = im.load(); w, h = im.size
            for y in range(h):
                for x in range(w):
                    if magenta(ip[x, y]): ip[x, y] = (0, 0, 0, 0)
            im = defringe(im)
            bb = im.getbbox()
            im = im.crop((bb[0], 0, bb[2], h))           # only the track, side to side
            im = im.resize((round(HEIGHT * RATIO), HEIGHT), Image.LANCZOS)
            # Soft ends, so a step melts into the ground under the places it joins.
            ip = im.load(); w, h = im.size
            for x in range(w):
                t = min(x, w - 1 - x) / (w * FADE)
                if t >= 1: continue
                k = t * t * (3 - 2 * t)
                for y in range(h):
                    r, g, b, a = ip[x, y]
                    ip[x, y] = (r, g, b, round(a * k))
            pieces.append(im)
    return pieces

kinds = [('ROADS', cut_sheet(sys.argv[1])), ('PAVED', cut_sheet(sys.argv[2]) if len(sys.argv) > 2 else [])]
pieces = [p for _, ps in kinds for p in ps]
aw = max(p.size[0] for p in pieces)
atlas = Image.new('RGBA', (aw, (HEIGHT + 2) * len(pieces)), (0, 0, 0, 0))
index, i = {}, 0
for name, ps in kinds:
    index[name] = []
    for p in ps:
        atlas.paste(p, (0, i * (HEIGHT + 2)))
        index[name].append([0, i * (HEIGHT + 2), p.size[0], p.size[1]]); i += 1
out = os.path.join(root, 'icons', 'roads.webp')
atlas.save(out, 'WEBP', quality=85, method=6)
js = ('// Generated by dev/build-roads.py: where each painted road piece sits in icons/roads.webp, [x, y, w, h].\n'
      '// ROADS is the dirt track, PAVED the cobbled lane it becomes.\n'
      f'export const SIZE = [{atlas.size[0]}, {atlas.size[1]}];\n'
      + ''.join(f'export const {name} = {json.dumps(index[name], separators=(",", ":"))};\n' for name, _ in kinds))
open(os.path.join(root, 'js', 'map', 'roads-atlas.js'), 'w', newline='\n').write(js)
print(f'{len(index["ROADS"])} dirt and {len(index["PAVED"])} paved pieces, atlas {atlas.size[0]}x{atlas.size[1]}, {os.path.getsize(out) // 1024} KB')
