# The painted ground tiles (made in Gemini, cut by hand from magenta sheets) packed into one image,
# icons/terrain.webp, and its index, js/map/terrain-atlas.js. One file, so the offline app needs one
# more entry in sw.js's SHELL, not a hundred.
#
#   python dev/build-terrain.py <tiles dir>
#
# Tiles are named <set>-<season>-<n>.png, e.g. meadow-autumn-2.png or uk-town-winter-1.png. Each is
# scaled so its hex base is BASE pixels wide (the widest sprite of its set is taken as the base:
# trees can spill a little past it, so the median of the set is used).
import sys, os, json, re, statistics
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from defringe import defringe

BASE = 160
SEASONS = ('autumn', 'late', 'winter', 'spring')
src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = sorted(f for f in os.listdir(src) if f.endswith('.png'))
parsed = []
for f in files:
    m = re.match(r'^(.+)-(autumn|late|winter|deep|spring)-(\d+)\.png$', f)
    if not m or m.group(2) not in SEASONS: continue
    parsed.append((m.group(1), m.group(2), int(m.group(3)), f))
# The base width of each set: the median width of its sprites.
widths = {}
for s, _, _, f in parsed: widths.setdefault(s, []).append(Image.open(os.path.join(src, f)).size[0])
ref = {s: statistics.median(w) for s, w in widths.items()}
sprites = []
for s, season, n, f in parsed:
    im = defringe(Image.open(os.path.join(src, f)))
    k = BASE / ref[s]
    im = im.resize((max(1, round(im.size[0] * k)), max(1, round(im.size[1] * k))), Image.LANCZOS)
    sprites.append((s, season, n, im))
cw = max(im.size[0] for *_, im in sprites) + 2
ch = max(im.size[1] for *_, im in sprites) + 2
cols = 16
rows = (len(sprites) + cols - 1) // cols
atlas = Image.new('RGBA', (cols * cw, rows * ch), (0, 0, 0, 0))
index = {}
for i, (s, season, n, im) in enumerate(sprites):
    x, y = (i % cols) * cw, (i // cols) * ch
    atlas.paste(im, (x, y))
    index.setdefault(s, {}).setdefault(season, []).append([x, y, im.size[0], im.size[1]])
out = os.path.join(root, 'icons', 'terrain.webp')
atlas.save(out, 'WEBP', quality=82, method=6)
js = ('// Generated by dev/build-terrain.py: where each painted ground tile sits in icons/terrain.webp.\n'
      '// [x, y, width, height] in the atlas; every tile is drawn so its hex base is BASE pixels wide.\n'
      f'export const BASE = {BASE};\nexport const SIZE = [{atlas.size[0]}, {atlas.size[1]}];\n'
      f'export const SETS = {json.dumps(index, separators=(",", ":"))};\n')
open(os.path.join(root, 'js', 'map', 'terrain-atlas.js'), 'w', newline='\n').write(js)
print(f'{len(sprites)} tiles, atlas {atlas.size[0]}x{atlas.size[1]}, {os.path.getsize(out) // 1024} KB')
print({s: {k: len(v) for k, v in d.items()} for s, d in index.items()})
