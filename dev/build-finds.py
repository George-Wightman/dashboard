# The painted finds (coal, sheep, a pit wheel...: made in Gemini as a 4x4 sheet on magenta) cut out and
# packed into icons/finds.webp, with their places in js/map/finds-atlas.js. Generic pictures, nothing
# private, so the sheet's cut-outs live in the repo.
#
#   python dev/build-finds.py <sheet.png>
#
# The sheet's cells, row by row, are the kinds in ORDER; a cell named None is left out.
import sys, os, json
from collections import deque
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from defringe import defringe

ORDER = ['coal', 'wheat', 'sheep', 'deer', 'horses', 'pub', 'pitwheel', 'stone',
         'salt', 'cows', 'timber', 'trout', 'marble', 'beer', 'fish', None]
HEIGHT = 96
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sheet = Image.open(sys.argv[1]).convert('RGBA')
W, H = sheet.size

def cut(cell):
    # The background: magenta (and the purple of its shadows) joined to the cell's edge.
    w, h = cell.size; px = cell.load()
    bg = [[False] * w for _ in range(h)]
    q = deque([(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)])
    while q:
        x, y = q.popleft()
        if bg[y][x]: continue
        r, g, b, _ = px[x, y]
        if not (r - g > 35 and b - g > 10): continue
        bg[y][x] = True
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and not bg[ny][nx]: q.append((nx, ny))
    for y in range(h):
        for x in range(w):
            if bg[y][x]: px[x, y] = (0, 0, 0, 0)
    cell = defringe(cell, inner=True)
    # Scraps of the neighbouring cells' pictures: only the pieces at least a quarter the size of the
    # biggest stay (two sheep are two pieces).
    px = cell.load(); seen = set(); parts = []
    for y in range(h):
        for x in range(w):
            if (x, y) in seen or px[x, y][3] < 100: continue
            q = deque([(x, y)]); seen.add((x, y)); part = []
            while q:
                cx, cy = q.popleft(); part.append((cx, cy))
                for nx, ny in ((cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)):
                    if 0 <= nx < w and 0 <= ny < h and (nx, ny) not in seen and px[nx, ny][3] >= 100: seen.add((nx, ny)); q.append((nx, ny))
            parts.append(part)
    big = max(len(p) for p in parts)
    for part in parts:
        if len(part) < big / 4:
            for x, y in part: px[x, y] = (0, 0, 0, 0)
    return cell.crop(cell.getbbox())

sprites = []
for i, kind in enumerate(ORDER):
    if not kind: continue
    x0, y0 = (i % 4) * W // 4, (i // 4) * H // 4
    im = cut(sheet.crop((x0, y0, x0 + W // 4, y0 + H // 4)))
    im = im.resize((max(1, round(im.size[0] * HEIGHT / im.size[1])), HEIGHT), Image.LANCZOS)
    sprites.append((kind, im))
cw = max(im.size[0] for _, im in sprites) + 2
atlas = Image.new('RGBA', (cw * 5, (HEIGHT + 2) * 3), (0, 0, 0, 0))
index = {}
for i, (kind, im) in enumerate(sprites):
    x, y = (i % 5) * cw, (i // 5) * (HEIGHT + 2)
    atlas.paste(im, (x, y))
    index[kind] = [x, y, im.size[0], im.size[1]]
out = os.path.join(root, 'icons', 'finds.webp')
atlas.save(out, 'WEBP', quality=85, method=6)
js = ('// Generated by dev/build-finds.py: where each painted find sits in icons/finds.webp, [x, y, w, h].\n'
      f'export const SIZE = [{atlas.size[0]}, {atlas.size[1]}];\n'
      f'export const FINDS = {json.dumps(index, separators=(",", ":"))};\n')
open(os.path.join(root, 'js', 'map', 'finds-atlas.js'), 'w', newline='\n').write(js)
print(f'{len(sprites)} finds, atlas {atlas.size[0]}x{atlas.size[1]}, {os.path.getsize(out) // 1024} KB')
